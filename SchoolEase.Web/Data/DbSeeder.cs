    /// <summary>
    /// Creates tables introduced after the first release. Hosted databases are
    /// built with EnsureCreated(), which never alters an existing schema, so any
    /// table added later has to be created explicitly. Uses CREATE TABLE IF NOT
    /// EXISTS so it is idempotent and safe to run on every application start.
    /// </summary>
    private static async Task EnsureSchemaAsync(ApplicationDbContext db)
    {
        var provider = db.Database.ProviderName ?? string.Empty;

        if (provider.Contains("Npgsql", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "LearningActivitySheets" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "Title" character varying(160) NOT NULL,
                    "Description" character varying(1000),
                    "SubjectId" integer NOT NULL,
                    "GradeLevelId" integer,
                    "Term" integer NOT NULL,
                    "WeekNumber" integer,
                    "MelcCode" character varying(40),
                    "Competency" character varying(400),
                    "FileName" character varying(260) NOT NULL,
                    "ContentType" character varying(120) NOT NULL,
                    "FileSize" bigint NOT NULL,
                    "FileContent" bytea NOT NULL,
                    "StorageKey" character varying(400),
                    "IsPublished" boolean NOT NULL,
                    "SchoolYear" character varying(20) NOT NULL,
                    "UploaderName" character varying(120) NOT NULL,
                    "UploadedByUserId" text,
                    "DownloadCount" integer NOT NULL,
                    "CreatedAt" timestamp without time zone NOT NULL,
                    "UpdatedAt" timestamp without time zone,
                    CONSTRAINT "FK_LearningActivitySheets_Subjects_SubjectId"
                        FOREIGN KEY ("SubjectId") REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
                    CONSTRAINT "FK_LearningActivitySheets_GradeLevels_GradeLevelId"
                        FOREIGN KEY ("GradeLevelId") REFERENCES "GradeLevels" ("Id") ON DELETE SET NULL
                );
                """);

            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_SubjectId\" ON \"LearningActivitySheets\" (\"SubjectId\");");
            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_GradeLevelId\" ON \"LearningActivitySheets\" (\"GradeLevelId\");");
            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_IsPublished\" ON \"LearningActivitySheets\" (\"IsPublished\");");

            // Databases created before object storage existed have no StorageKey
            // column. Idempotent, so it is safe to run on every start.
            await db.Database.ExecuteSqlRawAsync(
                "ALTER TABLE \"LearningActivitySheets\" ADD COLUMN IF NOT EXISTS \"StorageKey\" character varying(400);");
        }
        else if (provider.Contains("Sqlite", StringComparison.OrdinalIgnoreCase))
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "LearningActivitySheets" (
                    "Id" INTEGER NOT NULL CONSTRAINT "PK_LearningActivitySheets" PRIMARY KEY AUTOINCREMENT,
                    "Title" TEXT NOT NULL,
                    "Description" TEXT,
                    "SubjectId" INTEGER NOT NULL,
                    "GradeLevelId" INTEGER,
                    "Term" INTEGER NOT NULL,
                    "WeekNumber" INTEGER,
                    "MelcCode" TEXT,
                    "Competency" TEXT,
                    "FileName" TEXT NOT NULL,
                    "ContentType" TEXT NOT NULL,
                    "FileSize" INTEGER NOT NULL,
                    "FileContent" BLOB NOT NULL,
                    "StorageKey" TEXT,
                    "IsPublished" INTEGER NOT NULL,
                    "SchoolYear" TEXT NOT NULL,
                    "UploaderName" TEXT NOT NULL,
                    "UploadedByUserId" TEXT,
                    "DownloadCount" INTEGER NOT NULL,
                    "CreatedAt" TEXT NOT NULL,
                    "UpdatedAt" TEXT,
                    CONSTRAINT "FK_LearningActivitySheets_Subjects_SubjectId"
                        FOREIGN KEY ("SubjectId") REFERENCES "Subjects" ("Id") ON DELETE RESTRICT,
                    CONSTRAINT "FK_LearningActivitySheets_GradeLevels_GradeLevelId"
                        FOREIGN KEY ("GradeLevelId") REFERENCES "GradeLevels" ("Id") ON DELETE SET NULL
                );
                """);

            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_SubjectId\" ON \"LearningActivitySheets\" (\"SubjectId\");");
            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_GradeLevelId\" ON \"LearningActivitySheets\" (\"GradeLevelId\");");
            await db.Database.ExecuteSqlRawAsync(
                "CREATE INDEX IF NOT EXISTS \"IX_LearningActivitySheets_IsPublished\" ON \"LearningActivitySheets\" (\"IsPublished\");");

            // SQLite has no ADD COLUMN IF NOT EXISTS, so check first.
            if (!await SqliteColumnExistsAsync(db, "LearningActivitySheets", "StorageKey"))
            {
                await db.Database.ExecuteSqlRawAsync(
                    "ALTER TABLE \"LearningActivitySheets\" ADD COLUMN \"StorageKey\" TEXT;");
            }
        }
    }

    /// <summary>True when a SQLite table already has the given column.</summary>
    private static async Task<bool> SqliteColumnExistsAsync(ApplicationDbContext db, string table, string column)
    {
        var connection = db.Database.GetDbConnection();
        var opened = false;

        if (connection.State != System.Data.ConnectionState.Open)
        {
            await connection.OpenAsync();
            opened = true;
        }

        try
        {
            await using var command = connection.CreateCommand();
            command.CommandText = $"SELECT COUNT(*) FROM pragma_table_info('{table}') WHERE name = @name";
            var parameter = command.CreateParameter();
            parameter.ParameterName = "@name";
            parameter.Value = column;
            command.Parameters.Add(parameter);

            var result = await command.ExecuteScalarAsync();
            return Convert.ToInt64(result) > 0;
        }
        finally
        {
            if (opened) await connection.CloseAsync();
        }
    }

