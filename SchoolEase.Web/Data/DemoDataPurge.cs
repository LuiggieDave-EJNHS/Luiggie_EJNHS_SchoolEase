using Microsoft.EntityFrameworkCore;

namespace SchoolEase.Web.Data;

/// <summary>How many demo rows exist per area (and how many a purge would remove).</summary>
public sealed class DemoPurgeReport
{
    public int Users { get; set; }
    public int Guardians { get; set; }
    public int Students { get; set; }
    public int Teachers { get; set; }
    public int Staff { get; set; }
    public int Sections { get; set; }
    public int Enrollments { get; set; }
    public int AttendanceRecords { get; set; }
    public int GradeRecords { get; set; }
    public int TeacherSubjectAssignments { get; set; }
    public int ClassSchedules { get; set; }
    public int DocumentRequests { get; set; }
    public int Notifications { get; set; }
    public int Announcements { get; set; }
    public int SchoolEvents { get; set; }

    /// <summary>Rows that are kept because they are still in use by real records.</summary>
    public int SkippedSections { get; set; }

    public int Total =>
        Users + Guardians + Students + Teachers + Staff + Sections + Enrollments +
        AttendanceRecords + GradeRecords + TeacherSubjectAssignments + ClassSchedules +
        DocumentRequests + Notifications + Announcements + SchoolEvents;

    public bool IsEmpty => Total == 0;
}

