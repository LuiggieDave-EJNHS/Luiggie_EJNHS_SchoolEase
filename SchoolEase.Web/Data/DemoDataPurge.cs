    /// <summary>Counts everything a purge would remove. Read-only and cheap enough for a settings page.</summary>
    public static async Task<DemoPurgeReport> ScanAsync(ApplicationDbContext db)
    {
        var targets = await ResolveTargetsAsync(db);

        var report = new DemoPurgeReport
        {
            Users = targets.UserIds.Count,
            Guardians = targets.GuardianIds.Count,
            Students = targets.StudentIds.Count,
            Teachers = targets.TeacherIds.Count,
            Staff = targets.StaffIds.Count,
            Sections = targets.SectionIds.Count,

            Enrollments = await db.Enrollments.CountAsync(x =>
                targets.StudentIds.Contains(x.StudentId)
                || (x.SectionId != null && targets.SectionIds.Contains(x.SectionId.Value))),

            AttendanceRecords = await db.AttendanceRecords.CountAsync(x =>
                targets.StudentIds.Contains(x.StudentId) || targets.SectionIds.Contains(x.SectionId)),

            GradeRecords = await db.GradeRecords.CountAsync(x =>
                targets.StudentIds.Contains(x.StudentId) || targets.SectionIds.Contains(x.SectionId)),

            TeacherSubjectAssignments = await db.TeacherSubjectAssignments.CountAsync(x =>
                targets.TeacherIds.Contains(x.TeacherId) || targets.SectionIds.Contains(x.SectionId)),

            ClassSchedules = await db.ClassSchedules.CountAsync(x =>
                targets.TeacherIds.Contains(x.TeacherId) || targets.SectionIds.Contains(x.SectionId)),

            DocumentRequests = await db.DocumentRequests.CountAsync(x => targets.StudentIds.Contains(x.StudentId)),

            Notifications = await db.Notifications.CountAsync(x => targets.UserIds.Contains(x.UserId)),

            Announcements = await db.Announcements.CountAsync(x =>
                x.AuthorUserId != null && targets.UserIds.Contains(x.AuthorUserId)),

            SchoolEvents = await db.SchoolEvents.CountAsync(x => DemoEvents.Contains(x.Title))
        };

        return report;
    }

    /// <summary>
    /// Deletes the demo rows in foreign-key-safe order and returns what was removed.
    /// <paramref name="keepUserId"/> (normally the signed-in Super Administrator) is never deleted.
    /// </summary>
    public static async Task<DemoPurgeReport> PurgeAsync(ApplicationDbContext db, string? keepUserId)
    {
        var targets = await ResolveTargetsAsync(db);

        if (keepUserId is not null)
        {
            targets.UserIds.RemoveAll(id => id == keepUserId);
        }

        var report = new DemoPurgeReport();

        // ---------------------------------------------------------------
        // 1. Rows that hang off a demo learner.
        // ---------------------------------------------------------------
        report.DocumentRequests = await db.DocumentRequests
            .Where(x => targets.StudentIds.Contains(x.StudentId))
            .ExecuteDeleteAsync();

        report.AttendanceRecords = await db.AttendanceRecords
            .Where(x => targets.StudentIds.Contains(x.StudentId) || targets.SectionIds.Contains(x.SectionId))
            .ExecuteDeleteAsync();

        report.GradeRecords = await db.GradeRecords
            .Where(x => targets.StudentIds.Contains(x.StudentId) || targets.SectionIds.Contains(x.SectionId))
            .ExecuteDeleteAsync();

        report.Enrollments = await db.Enrollments
            .Where(x => targets.StudentIds.Contains(x.StudentId)
                || (x.SectionId != null && targets.SectionIds.Contains(x.SectionId.Value)))
            .ExecuteDeleteAsync();

        // ---------------------------------------------------------------
        // 2. Timetable rows. These reference sections and teachers with
        //    ON DELETE RESTRICT, so they must go before the people.
        // ---------------------------------------------------------------
        report.ClassSchedules = await db.ClassSchedules
            .Where(x => targets.TeacherIds.Contains(x.TeacherId) || targets.SectionIds.Contains(x.SectionId))
            .ExecuteDeleteAsync();

        report.TeacherSubjectAssignments = await db.TeacherSubjectAssignments
            .Where(x => targets.TeacherIds.Contains(x.TeacherId) || targets.SectionIds.Contains(x.SectionId))
            .ExecuteDeleteAsync();

        // ---------------------------------------------------------------
        // 3. Communications authored by the demo accounts.
        // ---------------------------------------------------------------
        report.Notifications = await db.Notifications
            .Where(x => targets.UserIds.Contains(x.UserId))
            .ExecuteDeleteAsync();

        report.Announcements = await db.Announcements
            .Where(x => x.AuthorUserId != null && targets.UserIds.Contains(x.AuthorUserId))
            .ExecuteDeleteAsync();

        report.SchoolEvents = await db.SchoolEvents
            .Where(x => DemoEvents.Contains(x.Title))
            .ExecuteDeleteAsync();

        // ---------------------------------------------------------------
        // 4. People.
        // ---------------------------------------------------------------
        report.Students = await db.Students
            .Where(x => targets.StudentIds.Contains(x.Id))
            .ExecuteDeleteAsync();

        report.Guardians = await db.Guardians
            .Where(x => targets.GuardianIds.Contains(x.Id))
            .ExecuteDeleteAsync();

        report.Teachers = await db.Teachers
            .Where(x => targets.TeacherIds.Contains(x.Id))
            .ExecuteDeleteAsync();

        report.Staff = await db.StaffMembers
            .Where(x => targets.StaffIds.Contains(x.Id))
            .ExecuteDeleteAsync();

        // ---------------------------------------------------------------
        // 5. Sections last, and only the ones nothing real still points at.
        //    The student purge above cleared the demo learners, so a section
        //    that still holds students is one the school actually uses.
        // ---------------------------------------------------------------
        var blocked = await db.Students
            .Where(x => x.SectionId != null && targets.SectionIds.Contains(x.SectionId.Value))
            .Select(x => x.SectionId!.Value)
            .Distinct()
            .ToListAsync();

        report.SkippedSections = blocked.Count;

        report.Sections = await db.Sections
            .Where(x => targets.SectionIds.Contains(x.Id) && !blocked.Contains(x.Id))
            .ExecuteDeleteAsync();

        return report;
    }

    /// <summary>The exact primary keys the demo seeders are known to have produced.</summary>
    private static async Task<PurgeTargets> ResolveTargetsAsync(ApplicationDbContext db)
    {
        var guardianIds = await db.Guardians
            .Where(g => g.Email != null && g.Email.StartsWith("guardian") && g.Email.EndsWith("@example.ph"))
            .Select(g => g.Id)
            .ToListAsync();

        return new PurgeTargets
        {
            GuardianIds = guardianIds,

            // Every demo learner was created with one of the demo guardians, so the
            // guardian link identifies them without touching real enrolments.
            StudentIds = await db.Students
                .Where(s => s.GuardianId != null && guardianIds.Contains(s.GuardianId.Value))
                .Select(s => s.Id)
                .ToListAsync(),

            TeacherIds = await db.Teachers
                .Where(t => DemoEmployeeNumbers.Contains(t.EmployeeNumber))
                .Select(t => t.Id)
                .ToListAsync(),

            StaffIds = await db.StaffMembers
                .Where(s => DemoStaffNumbers.Contains(s.StaffNumber))
                .Select(s => s.Id)
                .ToListAsync(),

            SectionIds = await db.Sections
                .Where(s => DemoSections.Contains(s.Code))
                .Select(s => s.Id)
                .ToListAsync(),

            UserIds = await db.Users
                .Where(u => u.Email != null && DemoUserEmails.Contains(u.Email))
                .Select(u => u.Id)
                .ToListAsync()
        };
    }

    private sealed class PurgeTargets
    {
        public List<string> UserIds { get; set; } = new();
        public List<int> GuardianIds { get; set; } = new();
        public List<int> StudentIds { get; set; } = new();
        public List<int> TeacherIds { get; set; } = new();
        public List<int> StaffIds { get; set; } = new();
        public List<int> SectionIds { get; set; } = new();
    }
}
